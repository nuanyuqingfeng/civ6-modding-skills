local function probe(inst, names, tag)
  local hit, miss = {}, {}
  for i=1,#names do
    local n=names[i]
    local v=nil
    local ok=pcall(function() v=inst[n] end)
    if ok and v~=nil then hit[#hit+1]=n..":"..type(v) else miss[#miss+1]=n end
  end
  print(tag.."|hit="..#hit.."|"..#names.."|"..table.concat(hit,","))
  print(tag.."|miss="..#miss.."|"..table.concat(miss,","))
end
local ctrl = Controls.Core or Controls.AdditionalUserInterfaces
probe(ctrl, CTL, "CTL_ControlBase")
probe(ctrl, CB, "CTL_CodeBuddy")
probe(ContextPtr, CTXP, "CTX_ContextPtr")
probe(ContextPtr, CTL, "CTX_Control")
